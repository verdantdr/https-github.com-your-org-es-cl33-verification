def bitcount_vec(m):
    return np.array([bin(b).count('1') for b in range(2 ** m)])


def word_action(w, m):
    """returns (perm, sign) with w|b> = sign[b] |perm[b]>, b read with the first factor as most significant bit."""
    s, x, z = w
    xi = int("".join(map(str, x)), 2)
    out_sign = np.empty(2 ** m, dtype=np.int64)
    perm = np.empty(2 ** m, dtype=np.int64)
    zb = int("".join(map(str, z)), 2)
    for b in range(2 ** m):
        # X^x Z^z |b> = (-1)^{z.b} |b xor x>
        out_sign[b] = s * (-1) ** (bin(zb & b).count('1') % 2)
        perm[b] = b ^ xi
    return perm, out_sign


def deltaN_content(terms, m):
    """terms: list of (coef, word).  Returns dict dN -> total |amplitude| of the operator sum_t coef*word on matrix
    entries <b'|X|b> grouped by dN = N(b') - N(b)."""
    nb = bitcount_vec(m)
    acc = {}
    amp = {}
    for coef, w in terms:
        perm, sg = word_action(w, m)
        for bb in range(2 ** m):
            key = (perm[bb], bb)
            amp[key] = amp.get(key, 0) + coef * sg[bb]
    for (bp, bb), v in amp.items():
        if v != 0:
            dN = nb[bp] - nb[bb]
            acc[dN] = acc.get(dN, 0) + abs(v)
    return acc


