def gf2_rank(vecs):
    rows = [int("".join(map(str, v)), 2) for v in vecs]
    rank = 0
    pivots = []
    for r in rows:
        for p in pivots:
            r = min(r, r ^ p)
        if r:
            pivots.append(r)
            rank += 1
    return rank


