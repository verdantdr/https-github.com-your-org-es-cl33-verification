def wmul(a, b):
    s1, x1, z1 = a
    s2, x2, z2 = b
    sign = s1 * s2 * (-1) ** (sum(p & q for p, q in zip(z1, x2)) % 2)
    return (sign, tuple(p ^ q for p, q in zip(x1, x2)), tuple(p ^ q for p, q in zip(z1, z2)))


def wprod(ws, m):
    r = (1, (0,) * m, (0,) * m)
    for w in ws:
        r = wmul(r, w)
    return r


def wkron(*ws):
    s, x, z = 1, (), ()
    for w in ws:
        s *= w[0]
        x += w[1]
        z += w[2]
    return (s, x, z)


